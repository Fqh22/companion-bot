"""[orchestration] 即时记忆：用户明确自述的事实，立刻落库，不等批量总结。

为什么要它：现在记忆要等「8 轮 / 40 条 / 闲置 30 分钟」才总结（SUMMARY_BATCH）。
你上午说「我下周三面试」，如果之后不再说话，这句话要等 30 分钟后的下一条消息才进记忆。
说「安全」是合理的——批量总结省调用、少碎片；代价是**记忆有延迟，而且延迟是静默的**。

这里只做最窄的一件事：从一条用户消息里挑出**明确自述**的那一句，原文写入。
不做事实抽取（那要模型调用），不做改写（改写会引入判断），只保证「说了就会被记住」。

风险控制：
- importance 记 0.35（低档）→ cleanup 30 天会清，不会永久占位；
- range_key 用消息 id 幂等 → 同一条消息重放不会写第二条；
- 只取命中句（不是整段），避免把闲聊也写进去。
"""
from __future__ import annotations

import re

# 只认「明确自述」。宁可漏，不可把「我觉得」「我在想」这类当事实。
_PATTERNS = (
    r"我(?:现在)?(?:住在|住|家在|老家在|搬到了|搬到)",
    r"我(?:叫|的名字是|姓)",
    r"我(?:在|是)(?:做|干|从事|负责)",
    r"我(?:的)?(?:老婆|老公|男朋友|女朋友|孩子|女儿|儿子|妈|爸|猫|狗)(?:叫|是|在)",
    r"我(?:明天|后天|大后天|下周[一二三四五六日天]|下个月|月底|今年|明年)",
    r"我(?:今年|去年|明年)\d{2,4}?岁",
)
_RE = [re.compile(p) for p in _PATTERNS]


def pick(text: str) -> str:
    """挑出一句明确自述；没有返回空串。"""
    for s in re.split(r"[。！？!?\n；;]", text or ""):
        s = s.strip()
        if not (5 <= len(s) <= 120):
            continue
        if any(r.search(s) for r in _RE):
            return s
    return ""
