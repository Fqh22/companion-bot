"""[domain] 分享轮档位：算「他给了多少授权」，给一个读深度的上限。

**不是分类器**：它不选模板、不决定说什么，只回答「这一轮最多说到第几档」。
判据与边界见 docs/17-分享轮.md，这里只做两件事：判档、写成一句可注入的上限。

为什么放在 prompt 外面算：模型看到「古风女子唱歌」会自己判成「可以聊歌」，
判不出「他一个字没说，所以最多到情绪层」。这个判断需要的是**行为事实**
（他配了几个字、东西是什么体裁），不是内容理解——代码算得比模型稳。
"""
from __future__ import annotations

import re

# 他说出口的意图/感受 → 第 4 档
_INTENT = ("我想", "我是要", "我要做", "我打算", "我觉得这", "你猜",
           "我做的", "我这个", "我准备")
# 明确要求 → 第 3 档
_ASK = ("你觉得", "是不是", "看看", "帮我", "怎么样", "好不好", "对不对",
        "能不能", "像不像", "哪个", "有啥")
# 情绪物体裁：转发的东西，默认只授权到情绪层
_EMO = ("表情包", "梗图", "Q版", "贴纸", "meme", "短视频", "歌曲", "歌",
        "音乐", "动漫", "二次元", "视频")
# 作品体裁：他自己做的东西，默认授权到机制层
_WORK = ("架构", "定义", "对比", "表格", "代码", "界面", "设计", "提示词",
         "实验", "指标", "日志", "测试", "文档", "列表", "按钮", "标题",
         "排版", "流程", "方案", "框架")

_PLACE = re.compile(r"^\[发了图片\]")
_CAPTION = re.compile(r"｜图注：[^\n]*")
_ATTACH = re.compile(r"（附了[^）]*）")

BLOCKS = {
    0: ("他什么都没说，只是把这个给你看。",
        "最多说到：这个东西本身是什么、带着什么情绪。"
        "不许解释他为什么发，不许连到他身上，不许判断他是什么人。"
        "下限：必须说出一个具体的点，不能只说「挺好的」「有意思」。"),
    1: ("这是他自己做的东西，但他没说要你看哪。",
        "可以读到它怎么运作、设计上在解决什么问题。"
        "不许评价好坏，不许猜他做它是为了什么。"
        "下限：必须指认一个具体的设计选择。"),
    2: ("他说了一句，但没指方向。",
        "可以接他的字，可以给一句自己的读法，别扩写成分析。"
        "不许替他解释这句话背后的动机。"
        "下限：必须指认这个东西的功能点。"),
    3: ("他明确要你看、或者问你了。",
        "可以给判断，也可以读设计和意图；先说清你读到了什么，再下结论。"),
    4: ("他自己说出了意图或感受。",
        "复述、接住都可以，也能连到你们共同经历过的事。"
        "别再替他解释他为什么这么想。"),
}


def clean(user_text: str) -> str:
    """去掉占位符与图注，得到他真说的话。"""
    t = _ATTACH.sub("", _CAPTION.sub("", _PLACE.sub("", user_text or "")))
    return t.strip().strip("｜ \n")


def genre(caption: str) -> str:
    """体裁：只从内容摘要判，不从他的字判。emo / work / other。"""
    if any(w in caption for w in _EMO):
        return "emo"
    if any(w in caption for w in _WORK):
        return "work"
    return "other"


def judge(user_text: str, caption: str = "") -> tuple[int, str]:
    """返回 (档位, 一句理由)。理由只用于日志和注入，不展示给人。"""
    said = clean(user_text)
    if any(k in said for k in _INTENT):
        return 4, "他说出了自己的意图"
    if any(k in said for k in _ASK):
        return 3, "他明确要你看/问你"
    if said:
        return 2, "他说了一句，没指方向"
    g = genre(caption)
    if g == "work":
        return 1, "无字，但这是他自己的作品"
    if g == "emo":
        return 0, "无字，转发的东西"
    return 0, "无字，内容也看不出来"


def block(tier: int, reason: str = "") -> str:
    """注入文本：一句上限 + 该档的允许/禁止 + 下限。"""
    head, body = BLOCKS.get(tier, BLOCKS[0])
    tag = "（%s）" % reason if reason else ""
    return "【这一轮的上限】%s%s\n%s" % (head, tag, body)
